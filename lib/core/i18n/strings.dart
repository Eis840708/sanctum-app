  static String catLabel(String key) {
    if (key.startsWith('custom:')) {
      final parts = key.split(':');
      if (parts.length >= 3) return '${parts[1]} ${parts.sublist(2).join(':')}';
      if (parts.length == 2) return parts[1];
    }
    return get(key);
  }

